#!/usr/bin/env python3
"""Write remotion/beats.ts: word-keyed camera steps (PLAYBOOK §10.6) wherever the scene code leaves a stretch of speech
longer than MAX s without a word-locked event, and on every spoken number no scene cue lands on.
The scene cues stay the film's choreography; these steps only move the desk camera on the word (Film.tsx beatCam).
Run from the repo root after any scene change: python3 films/lpt-goes-steel/scenes/beats_gen.py"""
import glob, json, re, sys
sys.path.insert(0, "scripts")
from sync_audit import NUM  # the audit's own number words
F = "films/lpt-goes-steel"
MAX = 1.35
t = json.load(open(f"{F}/vo/timing.json"))
fps = t["fps"]
cl = lambda w: re.sub(r"[^a-z0-9']", "", w.lower())
words = {}
for w in t["words"]:
    for p in [x for x in w["w"].split("—") if x]:
        words.setdefault(w["s"], []).append({"w": cl(p), "raw": p, "f": w["startFrame"]})
CUE = re.compile(r"""\bw(?:e)?f\(\s*(\d+)\s*,\s*(?:'([^']+)'|"([^"]+)")\s*(?:,\s*(\d+))?\s*\)""")
cued = {}
for f in glob.glob(f"{F}/remotion/**/*.ts*", recursive=True):
    if f.endswith("beats.ts"):
        continue
    for m in CUE.finditer(open(f).read()):
        s, w, n = int(m.group(1)), cl(m.group(2) or m.group(3)), int(m.group(4) or 0)
        hits = [x for x in words.get(s, []) if x["w"] == w]
        if len(hits) > n:
            cued.setdefault(s, set()).add(hits[n]["f"])
out = []
def lit(s, i):
    ws = words[s]; w = ws[i]["w"]; n = sum(1 for x in ws[:i] if x["w"] == w)
    raw = ws[i]['raw'].strip('.,:;?!"')
    return f"wf({s}, \"{raw}\"{', ' + str(n) if n else ''})"
for sent in t["sentences"]:
    s = sent["id"]; ws = words.get(s, [])
    have = set(cued.get(s, set()))
    for i, x in enumerate(ws):  # numbers first
        if any(p in NUM for p in re.split(r"-", x["w"])) and x["f"] not in have:
            have.add(x["f"]); out.append(lit(s, i))
    while True:  # then the longest gap, until none is over MAX
        pts = sorted(have | {sent["startFrame"], sent["endFrame"]})
        gaps = [(b - a, a, b) for a, b in zip(pts, pts[1:])]
        g, a, b = max(gaps)
        if g / fps <= MAX:
            break
        mid = (a + b) / 2
        cand = [(abs(x["f"] - mid), i) for i, x in enumerate(ws) if a < x["f"] < b and x["f"] not in have]
        if not cand:
            break
        i = min(cand)[1]; have.add(ws[i]["f"]); out.append(lit(s, i))
src = "import {wf} from './timing';\n\n// Generated by scenes/beats_gen.py: word-keyed desk-camera steps where the scene cues leave a gap or a number.\n" \
      f"// {len(out)} steps. Do not edit by hand.\nexport const BEATS: number[] = [\n" + "".join(f"\t{x},\n" for x in out) + "].sort((a, b) => a - b);\n"
open(f"{F}/remotion/beats.ts", "w").write(src)
print(len(out), "beats")
